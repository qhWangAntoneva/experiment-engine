"""Console-based renderer for experiment-engine.

Provides rich terminal output including formatted tables, summary
statistics, progress bars, and simple ASCII visualisations.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List, Optional, Union

import numpy as np

from experiment_engine.models import InputData, RenderConfig
from experiment_engine.viz.base import Renderer


class ConsoleRenderer(Renderer):
    """Renders experiment data to the terminal using the Rich library.

    Produces formatted tables, summary statistics, progress bars, and
    simple ASCII plots for quick inspection in the console.

    Examples:
        >>> renderer = ConsoleRenderer()
        >>> result = renderer.render(data)
        >>> print(result)  # rich-formatted output
    """

    @property
    def name(self) -> str:
        return "console"

    def render(
        self,
        data: InputData,
        config: RenderConfig,
        **kwargs: Any,
    ) -> str:
        """Render data as a rich-formatted console string.

        Args:
            data: Input data to display.
            config: Visualisation configuration (used for title).
            **kwargs: Additional options:
                show_table (bool): Print the data table (default: True).
                show_stats (bool): Print summary statistics (default: True).
                show_progress (bool): Show a progress bar (default: False).
                max_rows (int): Maximum table rows to display (default: 20).
                output_path (str): If provided, write output to file.

        Returns:
            str: The rendered console output as a plain string.
        """
        from rich.console import Console
        from rich.table import Table
        from rich.progress import Progress, BarColumn, TextColumn
        from rich.panel import Panel
        from rich.text import Text
        from rich import box

        show_table = kwargs.get("show_table", True)
        show_stats = kwargs.get("show_stats", True)
        show_progress = kwargs.get("show_progress", False)
        max_rows = kwargs.get("max_rows", 20)
        output_path = kwargs.get("output_path")

        console = Console(force_terminal=True, width=120)
        lines: List[str] = []

        # Helper to capture output
        class CaptureConsole(Console):
            """Console subclass that captures output to a list."""

            def __init__(self, *args: Any, **kwargs: Any) -> None:
                super().__init__(*args, **kwargs)
                self._captured: List[str] = []

            def print(self, *obj: Any, **kw: Any) -> None:
                # Capture text representation
                for item in obj:
                    self._captured.append(str(item))
                super().print(*obj, **kw)

        capture = CaptureConsole(force_terminal=True, width=120)

        # Title
        title = config.title if config.title else "Experiment Data Summary"
        capture.print()
        capture.print(Panel(Text(title, justify="center", style="bold cyan")))
        capture.print()

        # Dataset info
        info_text = (
            f"[bold]Samples:[/] {data.n_samples}  "
            f"[bold]Features:[/] {data.n_features}  "
            f"[bold]Shape:[/] {data.shape}"
        )
        capture.print(info_text)
        capture.print()

        # Progress bar simulation
        if show_progress:
            with Progress(
                TextColumn("[progress.description]{task.description}"),
                BarColumn(),
                TextColumn("[progress.percentage]{task.percentage:>3.0f}%"),
                console=capture,
            ) as progress:
                task = progress.add_task("[cyan]Rendering...", total=100)
                for _ in range(101):
                    progress.update(task, advance=1)

        # Summary statistics
        if show_stats:
            self._print_stats(capture, data)

        # Data table
        if show_table:
            self._print_table(capture, data, max_rows)

        # Footer
        capture.print()
        capture.print(
            Panel(
                Text(
                    f"Generated by experiment-engine ConsoleRenderer",
                    justify="center",
                    style="dim italic",
                )
            )
        )

        # Build output string
        output = "\n".join(capture._captured) if hasattr(capture, "_captured") else ""

        # Write to file if requested
        if output_path:
            path = Path(output_path)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(output, encoding="utf-8")

        return output

    def _print_stats(self, console: Any, data: InputData) -> None:
        """Print summary statistics with a Rich table.

        Args:
            console: Rich Console instance.
            data: Input data to summarise.
        """
        from rich.table import Table
        from rich import box

        table = Table(
            title="Summary Statistics",
            box=box.ROUNDED,
            show_header=True,
            header_style="bold cyan",
        )

        table.add_column("Feature", style="cyan")
        table.add_column("Mean", justify="right")
        table.add_column("Std", justify="right")
        table.add_column("Min", justify="right")
        table.add_column("25%", justify="right")
        table.add_column("50%", justify="right")
        table.add_column("75%", justify="right")
        table.add_column("Max", justify="right")

        for i in range(data.n_features):
            col = data.data[:, i]
            name = data.columns[i] if data.columns and i < len(data.columns) else f"F{i}"
            table.add_row(
                name,
                f"{np.mean(col):.4f}",
                f"{np.std(col):.4f}",
                f"{np.min(col):.4f}",
                f"{np.percentile(col, 25):.4f}",
                f"{np.percentile(col, 50):.4f}",
                f"{np.percentile(col, 75):.4f}",
                f"{np.max(col):.4f}",
            )

        console.print(table)
        console.print()

    def _print_table(
        self,
        console: Any,
        data: InputData,
        max_rows: int = 20,
    ) -> None:
        """Print the data values in a Rich table.

        Args:
            console: Rich Console instance.
            data: Input data to display.
            max_rows: Maximum number of rows to show.
        """
        from rich.table import Table
        from rich import box

        n_rows = min(data.n_samples, max_rows)
        truncated = data.n_samples > max_rows

        table = Table(
            title=f"Data Values (showing {n_rows} of {data.n_samples} rows)",
            box=box.SIMPLE,
            show_header=True,
            header_style="bold green",
            show_lines=False,
        )

        if data.index is not None:
            table.add_column("Index", style="dim")

        for c in data.columns:
            table.add_column(c, justify="right")

        for i in range(n_rows):
            row: List[str] = []
            if data.index is not None:
                row.append(str(data.index[i]))
            for val in data.data[i]:
                row.append(f"{val:.4f}" if isinstance(val, (int, float)) else str(val))
            table.add_row(*row)

        if truncated:
            table.add_row(
                *(["..."] * (len(data.columns) + (1 if data.index is not None else 0)))
            )

        console.print(table)

    def progress_bar(self, total: int = 100, description: str = "Processing") -> str:
        """Generate an inline progress bar string.

        Args:
            total: Total number of steps.
            description: Label for the progress bar.

        Returns:
            str: ASCII progress bar representation.
        """
        from rich.progress import Progress, BarColumn, TextColumn
        from rich.console import Console

        console = Console(width=80, force_terminal=True)
        output_lines: List[str] = []

        class StringConsole(Console):
            def print(self, *args: Any, **kwargs: Any) -> None:
                for arg in args:
                    output_lines.append(str(arg))

        sc = StringConsole(width=80, force_terminal=True)

        with Progress(
            TextColumn("[progress.description]{task.description}"),
            BarColumn(),
            TextColumn("[progress.percentage]{task.percentage:>3.0f}%"),
            console=sc,
        ) as progress:
            task = progress.add_task(description, total=total)
            for _ in range(total + 1):
                progress.update(task, advance=1)

        return "\n".join(output_lines)
